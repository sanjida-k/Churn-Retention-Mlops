// Expand seeds synthetically to create 120 rich records for interactive filtering, tables, and segmentation
function generateFullCustomerBase(): TelecomCustomer[] {
  const result: TelecomCustomer[] = [];
  const firstNames = ['Liam', 'Emma', 'Noah', 'Olivia', 'Ethan', 'Sophia', 'Lucas', 'Mia', 'Aarav', 'Ananya', 'Vivaan', 'Diya', 'Mateo', 'Isabella', 'Daniel', 'Fatima', 'Tariq', 'Zoe', 'Kenji', 'Hiroshi', 'Chen', 'Mei', 'Sven', 'Astrid'];
  const lastNames = ['Smith', 'Johnson', 'Williams', 'Brown', 'Jones', 'Garcia', 'Miller', 'Davis', 'Rodriguez', 'Martinez', 'Patel', 'Sharma', 'Singh', 'Kumar', 'Ali', 'Kim', 'Tanaka', 'Wang', 'Mueller', 'Dubois', 'Nielsen'];

  // First push our curated seeds
  rawCustomerSeeds.forEach((seed) => {
    const scored = calculateChurnProbability({
      contract: seed.contract,
      tenureMonths: seed.tenureMonths,
      monthlyCharges: seed.monthlyCharges,
      internetService: seed.internetService,
      techSupport: seed.techSupport,
      onlineSecurity: seed.onlineSecurity,
      paymentMethod: seed.paymentMethod,
      seniorCitizen: seed.seniorCitizen,
      supportTicketsLast90d: seed.supportTicketsLast90d,
      networkComplaints: seed.networkComplaints,
      paperlessBilling: seed.paperlessBilling,
    });

    result.push({
      ...seed,
      churnProbability: scored.probability,
      predictedChurn: scored.probability >= 0.5,
      riskLevel: scored.riskLevel,
      shapContributions: scored.contributions,
      recommendedAction: scored.recommendedAction,
    });
  });

  const existingIds = new Set(result.map(c => c.id));

  // Now procedurally generate remaining 108 records to reach 120 realistic subscribers
  for (let i = 13; i <= 120; i++) {
    const fn = firstNames[i % firstNames.length];
    const ln = lastNames[(i * 3) % lastNames.length];
    const contractTypes = ['Month-to-month', 'One year', 'Two year'] as const;
    const internetTypes = ['Fiber optic', 'DSL', '5G Home', 'No'] as const;
    const paymentTypes = ['Electronic check', 'Credit card (automatic)', 'Bank transfer (automatic)', 'Mailed check'] as const;

    // Skew distribution to reflect real telecom: ~50% month-to-month, ~45% fiber, ~26% churn
    const contract = i % 2 === 0 ? 'Month-to-month' : (i % 5 === 0 ? 'Two year' : 'One year');
    const internetService = i % 4 === 0 ? '5G Home' : (i % 3 === 0 ? 'DSL' : (i % 7 === 0 ? 'No' : 'Fiber optic'));
    const paymentMethod = i % 3 === 0 ? 'Electronic check' : (i % 2 === 0 ? 'Credit card (automatic)' : 'Bank transfer (automatic)');
    const tenureMonths = contract === 'Month-to-month' ? Math.max(1, (i * 7) % 36) : Math.max(12, (i * 11) % 72);
    
    let monthlyCharges = 45;
    if (internetService === 'Fiber optic') monthlyCharges = 75 + ((i * 13) % 40);
    else if (internetService === '5G Home') monthlyCharges = 60 + ((i * 7) % 25);
    else if (internetService === 'DSL') monthlyCharges = 35 + ((i * 5) % 25);
    else monthlyCharges = 20 + ((i * 3) % 15);

    const techSupport = i % 3 !== 0;
    const onlineSecurity = i % 2 === 0;
    const supportTickets = contract === 'Month-to-month' ? (i % 4) : (i % 2);
    const networkComplaints = supportTickets > 2 ? 2 : (i % 3 === 0 ? 1 : 0);

    const scored = calculateChurnProbability({
      contract,
      tenureMonths,
      monthlyCharges,
      internetService,
      techSupport,
      onlineSecurity,
      paymentMethod,
      seniorCitizen: i % 6 === 0,
      supportTicketsLast90d: supportTickets,
      networkComplaints,
      paperlessBilling: true,
    });

    let segment = 'Standard Consumer';
    if (scored.riskLevel === 'High' && monthlyCharges > 80) segment = 'High-Spender At Risk';
    else if (scored.riskLevel === 'High' && tenureMonths <= 6) segment = 'Budget Early Drop';
    else if (scored.riskLevel === 'Low' && tenureMonths > 36) segment = 'Enterprise Family Loyalist';
    else if (internetService === '5G Home') segment = '5G Modern Streamer';
    else if (internetService === 'No') segment = 'Voice Only Anchor';
    else if (monthlyCharges > 90) segment = 'Premium Fiber Family';

    let customerId = `TEL-${2000 + i}`;
    while (existingIds.has(customerId)) {
      customerId = `TEL-${3000 + i}`;
    }
    existingIds.add(customerId);

    result.push({
      id: customerId,
      name: `${fn} ${ln}`,
      email: `${fn.toLowerCase()}.${ln.toLowerCase()}@domain-${i}.com`,
      phone: `+1 (555) ${100 + (i * 7)}-${1000 + (i * 31)}`,
      gender: i % 2 === 0 ? 'Male' : 'Female',
      seniorCitizen: i % 6 === 0,
      partner: i % 2 === 0,
      dependents: i % 3 === 0,
      tenureMonths,
      phoneService: true,
      multipleLines: i % 2 === 0,
      internetService,
      onlineSecurity,
      onlineBackup: i % 2 === 0,
      deviceProtection: i % 3 === 0,
      techSupport,
      streamingTV: i % 2 === 0,
      streamingMovies: i % 2 === 0,
      contract,
      paperlessBilling: true,
      paymentMethod,
      monthlyCharges: Number(monthlyCharges.toFixed(2)),
      totalCharges: Number((monthlyCharges * tenureMonths).toFixed(2)),
      dataUsageGB: Math.round(monthlyCharges * 4.5 + (i * 17) % 200),
      npsScore: scored.riskLevel === 'High' ? Math.max(1, 6 - supportTickets) : Math.min(10, 7 + (i % 4)),
      supportTicketsLast90d: supportTickets,
      networkComplaints,
      churnProbability: scored.probability,
      predictedChurn: scored.probability >= 0.5,
      riskLevel: scored.riskLevel,
      shapContributions: scored.contributions,
      recommendedAction: scored.recommendedAction,
      segment,
      clv: Math.round(monthlyCharges * Math.max(12, tenureMonths * 0.8)),
    });
  }

  return result;
}

